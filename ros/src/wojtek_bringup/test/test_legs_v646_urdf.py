"""The v6.46 legs in the URDF: the v6.27 joints, the CAD's parts.

legs_v646 shares the leg macro (joints, axes in the drives' sense) with
legs_v627 and takes its links from the CAD export (legs_v646_links.urdf.xacro,
generated by training's import_robot). So: the joints must equal v6.27's
except the lever's folding limit, the masses must equal the MuJoCo model's
of the same export, and the collision of every leg link must be the link's
exact mesh (the owner's requirement, 2026-11-15: the outline as built,
because lying is decided by contacts).
"""

import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest
from ament_index_python.packages import get_package_share_directory

XACRO = f"{get_package_share_directory('wojtek_bringup')}/urdf/wojtek_real.urdf.xacro"
DESC = Path(get_package_share_directory("wojtek_description"))
LEGS = ("rear_left", "rear_right", "front_right", "front_left")
LINKS = ("third", "fourth", "fifth", "sixth")


def _urdf(legs):
    cmd = ["xacro", XACRO, f"legs:={legs}", "kp:=1", "kd:=1", "max_torque:=1"]
    return ET.fromstring(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


@pytest.fixture(scope="module")
def v627():
    return _urdf("legs_v627")


@pytest.fixture(scope="module")
def v646():
    return _urdf("legs_v646")


def _joints(root):
    return {j.get("name"): j for j in root.iter("joint") if j.find("parent") is not None}


def test_joints_are_the_v627_four_bar(v627, v646):
    a, b = _joints(v627), _joints(v646)
    legs_only = lambda js: {n for n in js if n.split("_")[0] in ("rear", "front")}
    assert legs_only(a) == legs_only(b)
    for name in legs_only(a):
        ja, jb = a[name], b[name]
        assert ja.get("type") == jb.get("type"), name
        for tag in ("origin", "axis"):
            ea, eb = ja.find(tag), jb.find(tag)
            assert (ea is None) == (eb is None), name
            if ea is not None:
                assert ea.attrib == eb.attrib, (name, tag)
        la, lb = ja.find("limit"), jb.find("limit")
        if la is not None and not name.endswith("_third_joint"):
            assert la.attrib == lb.attrib, name


def test_lever_folds_to_the_v646_stop(v646):
    # 18.0 deg, the controller's limit (the shin meets the stringer at 17.0)
    for leg in LEGS:
        lim = _joints(v646)[f"{leg}_third_joint"].find("limit")
        lo, hi = float(lim.get("lower")), float(lim.get("upper"))
        assert min(abs(lo), abs(hi)) == pytest.approx(0.314159265, abs=1e-6), leg


def test_masses_are_the_mujoco_models(v646):
    mj = ET.parse(DESC / "mujoco" / "legs_v646" / "wojtek.xml").getroot()
    mj_mass = {b.get("name"): float(b.find("inertial").get("mass"))
               for b in mj.iter("body") if b.find("inertial") is not None}
    links = {l.get("name"): l for l in v646.iter("link")}
    for leg in LEGS:
        for link in LINKS:
            name = f"{leg}_{link}_link"
            m = float(links[name].find("inertial/mass").get("value"))
            assert m == pytest.approx(mj_mass[name], rel=1e-5), name


def test_collision_is_the_exact_mesh(v646):
    links = {l.get("name"): l for l in v646.iter("link")}
    for leg in LEGS:
        for link in LINKS:
            el = links[f"{leg}_{link}_link"]
            vis = el.find("visual/geometry/mesh").get("filename")
            cols = [c.find("geometry/mesh").get("filename") for c in el.findall("collision")]
            assert cols == [vis], (leg, link, cols)
            path = DESC / vis.split("package://wojtek_description/")[1]
            assert path.is_file(), path


def test_standoffs_hang_under_the_base(v646, v627):
    names = {l.get("name") for l in v646.iter("link")}
    assert {f"standoff_{i}_link" for i in range(4)} <= names
    assert not any(l.get("name").startswith("standoff") for l in v627.iter("link"))
