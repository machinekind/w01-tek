"""Import a CAD-exported robot archive as the source model of a robot variant.

The mechanical team ships a leg design as a `sim_robot` archive: robot.xml
(MJCF), robot.urdf, loop_closure.yaml and a meshes/ directory. That MJCF is
a viewer scene, not a source model: it carries its own floor, light and
<option>, and its collision is several hundred convex pieces per leg, which
no batched backend can afford. This script turns it into the same kind of
file as wojtek.xml, robot only, and leaves the rest to build_model:

  - the floor, the light, <option> and the convex collision pieces
    (`col_*` meshes and the geoms that use them) are dropped from the
    source model; the pieces themselves are copied to
    wojtek_description/meshes/<robot>/collision/ and listed per body in
    mujoco/<robot>/collision.json, from which build_model makes the
    contact model (exact outline, floor-only, for lying and fallen poses)
  - the export's URDF links (inertial, visual mesh, collision meshes as
    exported: the exact mesh of the link, or its convex pieces) are written
    as one xacro macro per link to
    wojtek_description/urdf/<robot>_links.urdf.xacro, which the leg macro
    calls; the joints stay in the leg macro, in the drives' convention
  - meshes the variant shares with the stock robot keep pointing at
    wojtek_description/meshes; the variant's own visual meshes are copied
    to wojtek_description/meshes/<robot>/
  - names, joints, inertials, actuators, sensors, the loop-closure
    equalities and the CAD keyframe are kept exactly as exported

    ./run.sh import-robot --robot legs_v627 --archive ../sim_robot_v627.tgz
"""

import argparse
import json
import shutil
import tarfile
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from wojtek_rl import paths, robots

# Where the generated URDF link macros go (beside the leg macros).
URDF_DIR = paths.MESH_DIR.parent / "urdf"

# Prefix of the convex-decomposition collision meshes in the export.
COLLISION_MESH_PREFIX = "col_"


def _find_export(root: Path) -> Path:
    hits = sorted(root.rglob("robot.xml"))
    if len(hits) != 1:
        raise FileNotFoundError(f"expected one robot.xml under {root}, found {hits}")
    return hits[0].parent


def convert(export_dir: Path, robot: str) -> tuple[ET.ElementTree, list[str]]:
    """The source-model tree for `robot`, and the mesh files it must copy."""
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    tree = ET.parse(export_dir / "robot.xml", parser=parser)
    top = tree.getroot()
    top.set("model", f"wojtek_{robot}")

    for option in top.findall("option"):
        top.remove(option)

    shared = {p.name for p in paths.MESH_DIR.glob("*.stl")}
    own_meshes = []
    asset = top.find("asset")
    for mesh in list(asset.findall("mesh")):
        if mesh.get("name").startswith(COLLISION_MESH_PREFIX):
            asset.remove(mesh)
        elif mesh.get("file") not in shared:
            own_meshes.append(mesh.get("file"))
            mesh.set("file", f"{robot}/{mesh.get('file')}")
    top.find("compiler").set("meshdir", "../../meshes")

    world = top.find("worldbody")
    for child in list(world):
        if child.tag != "body":
            world.remove(child)
    for parent in world.iter():
        for geom in list(parent.findall("geom")):
            if geom.get("mesh", "").startswith(COLLISION_MESH_PREFIX):
                parent.remove(geom)
    return tree, own_meshes


def collision_pieces(export_dir: Path) -> dict[str, list[str]]:
    """Body name -> the convex-piece mesh files of its collision, in the
    export's order. The pieces sit in the body's frame (no pos/quat)."""
    tree = ET.parse(export_dir / "robot.xml")
    files = {m.get("name"): m.get("file") for m in tree.getroot().iter("mesh")}
    out: dict[str, list[str]] = {}
    for body in tree.getroot().iter("body"):
        for geom in body.findall("geom"):
            mesh = geom.get("mesh", "")
            if not mesh.startswith(COLLISION_MESH_PREFIX):
                continue
            if geom.get("pos") or geom.get("quat"):
                raise ValueError(f"{geom.get('name')}: a convex piece with an offset")
            out.setdefault(body.get("name"), []).append(files[mesh])
    return out


def urdf_links_xacro(export_dir: Path, robot: str) -> str:
    """One xacro macro per leg link of the export's URDF, named
    `<robot>_<link>` and taking no parameters: the link's inertial, visual
    mesh and collision meshes as exported. A collision mesh that is a convex
    piece lives in collision/, any other is one of the variant's meshes."""
    tree = ET.parse(export_dir / "robot.urdf")
    pkg = f"package://wojtek_description/meshes/{robot}"
    out = ['<?xml version="1.0"?>',
           f'<!-- GENERATED by training/wojtek_rl/import_robot.py from the CAD',
           f'     export of {robot}; do not edit by hand. One macro per link;',
           '     the joints, in the drives\' convention, are in leg_v627.urdf.xacro. -->',
           '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">']
    n = 0
    for link in tree.getroot().findall("link"):
        name = link.get("name")
        visual = link.find("visual")
        if visual is None or not any(
            name.endswith(f"_{s}_link") for s in ("third", "fourth", "fifth", "sixth")
        ):
            continue
        n += 1
        out.append(f'  <xacro:macro name="{robot}_{name}">')
        out.append(f'    <link name="{name}">')
        vfile = Path(visual.find("geometry/mesh").get("filename")).name
        out.append('      <visual><origin xyz="0 0 0" rpy="0 0 0"/><geometry>'
                   f'<mesh filename="{pkg}/{vfile}"/></geometry><xacro:grey_material/></visual>')
        for k, col in enumerate(link.findall("collision")):
            cfile = Path(col.find("geometry/mesh").get("filename")).name
            sub = "collision/" if cfile.startswith(COLLISION_MESH_PREFIX) else ""
            out.append(f'      <collision name="{name}_col{k}"><origin xyz="0 0 0" rpy="0 0 0"/>'
                       f'<geometry><mesh filename="{pkg}/{sub}{cfile}"/></geometry></collision>')
        inertial = link.find("inertial")
        out.append("      " + ET.tostring(inertial, encoding="unicode").strip())
        out.append("    </link>")
        out.append("  </xacro:macro>")
    out.append("</robot>")
    if n != 16:
        raise ValueError(f"expected 16 leg links with meshes in robot.urdf, found {n}")
    return "\n".join(out) + "\n"


def import_robot(archive: Path, robot: str) -> None:
    robots.get(robot)  # a variant is declared in robots.py before it is imported
    files = paths.robot_files(robot)
    with tempfile.TemporaryDirectory() as tmp:
        if archive.is_dir():
            export_dir = _find_export(archive)
        else:
            with tarfile.open(archive) as tar:
                tar.extractall(tmp, filter="data")
            export_dir = _find_export(Path(tmp))
        tree, own_meshes = convert(export_dir, robot)
        mesh_dir = paths.MESH_DIR / robot
        mesh_dir.mkdir(parents=True, exist_ok=True)
        for name in own_meshes:
            shutil.copyfile(export_dir / "meshes" / name, mesh_dir / name)
        pieces = collision_pieces(export_dir)
        col_dir = mesh_dir / "collision"
        if col_dir.exists():
            shutil.rmtree(col_dir)          # no stale pieces of an older export
        col_dir.mkdir()
        for name in sorted({f for fs in pieces.values() for f in fs}):
            shutil.copyfile(export_dir / "meshes" / name, col_dir / name)
        files["collision"].parent.mkdir(parents=True, exist_ok=True)
        files["collision"].write_text(json.dumps(pieces, indent=1) + "\n")
        links = URDF_DIR / f"{robot}_links.urdf.xacro"
        links.write_text(urdf_links_xacro(export_dir, robot))
    files["source"].parent.mkdir(parents=True, exist_ok=True)
    ET.indent(tree, space="  ")
    tree.write(files["source"], encoding="unicode")
    print(f"wrote {files['source']}")
    print(f"copied {len(own_meshes)} meshes to {mesh_dir}")
    print(f"copied {sum(len(v) for v in pieces.values())} convex pieces of "
          f"{len(pieces)} bodies to {col_dir}; wrote {files['collision']}, {links}")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--robot", required=True, choices=robots.NAMES)
    p.add_argument("--archive", required=True, type=Path,
                   help="sim_robot .tgz, or a directory it was unpacked into")
    args = p.parse_args()
    import_robot(args.archive, args.robot)


if __name__ == "__main__":
    main()
